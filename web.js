let idiomaActual = 'en';

function cambiarIdioma(idioma) {
  idiomaActual = idioma;
  for (const id in textos) {
    const el = document.getElementById(id);
    if (el) el.innerHTML = textos[id][idioma];
  }
  actualizarTooltips();
  mostrarToast(idioma === 'es' ? "has cambiado a Español" : "you have changed to English");
}

const mensajesHover = {
  linkedin: { en: "View LinkedIn profile", es: "Ver perfil de LinkedIn" },
  github: { en: "View GitHub profile", es: "Ver perfil de GitHub" },
  instagram: { en: "View Instagram profile", es: "Ver perfil de Instagram" },
  gmail: { en: "Send an email", es: "Enviar un email" },
  cv: { en: "Read CV", es: "Leer curriculum" },
  idioma: { en: "Language selector", es: "Selector de idiomas" },
  theme: { en: "Change theme", es: "Cambiar tema" }
};

const mensajesClick = {
  linkedin: { en: "Opening LinkedIn...", es: "Abriendo LinkedIn..." },
  github: { en: "Opening GitHub...", es: "Abriendo GitHub..." },
  instagram: { en: "Opening Instagram...", es: "Abriendo Instagram..." },
  gmail: { en: "Opening email client...", es: "Abriendo cliente de email..." },
  cv: { en: "Downloading CV...", es: "Descargando CV..." }
};

function actualizarTooltips() {
  document.querySelectorAll('[data-tooltip-key]').forEach(el => {
    const key = el.dataset.tooltipKey;
    if (mensajesHover[key]) {
      el.setAttribute('data-tooltip', mensajesHover[key][idiomaActual]);
    }
  });
}

function mostrarToast(texto) {
  const container = document.getElementById('toast-container');

  const MAX_TOASTS = 4;
  while (container.children.length >= MAX_TOASTS) {
    container.firstElementChild.remove();
  }

  const toast = document.createElement('div');
  toast.className = 'toast';
  toast.textContent = texto;
  container.appendChild(toast);

  requestAnimationFrame(() => toast.classList.add('mostrar'));

  setTimeout(() => {
    toast.classList.remove('mostrar');
    toast.addEventListener('transitionend', () => toast.remove(), { once: true });
  }, 2500);
}

document.querySelectorAll('[data-tooltip-key]').forEach(el => {
  const key = el.dataset.tooltipKey;
  if (key === 'idioma') return;
  const link = el.querySelector('a');
  if (link) {
    link.addEventListener('click', () => {
      if (mensajesClick[key]) mostrarToast(mensajesClick[key][idiomaActual]);
    });
  }
});

document.addEventListener('DOMContentLoaded', actualizarTooltips);

document.querySelectorAll('.card-header').forEach(header => {
 header.style.cursor = 'pointer';
  header.addEventListener('click', () => {
    const contenido = header.closest('section').querySelector('.contenido');

    if (contenido.classList.contains('activo')) {
      contenido.style.maxHeight = "0px";
      contenido.classList.remove('activo');
    } else {
      contenido.style.maxHeight = contenido.scrollHeight + "px";
      contenido.classList.add('activo');
    }
  });
});

function ajustarScrollIconos() {
  document.querySelectorAll('.skills-icons').forEach(container => {
    const track = container.querySelector('.skills-icons-track');
    if (!track) return;

    const originales = track.querySelectorAll('img:not([aria-hidden])');
    let anchoOriginales = 0;
    originales.forEach(img => { anchoOriginales += img.offsetWidth; });
    anchoOriginales += (originales.length - 1) * 15; // gaps entre íconos

    if (anchoOriginales <= container.clientWidth) {
      container.classList.add('fits');
    } else {
      container.classList.remove('fits');
    }
  });
}

const changeBtn = document.getElementById('themechanger');

const mensajesTema = {
  light: { en: "Light theme on", es: "Tema claro activado" },
  dark: { en: "Dark theme on", es: "Tema oscuro activado" }
};

function mensaTema(tema) {
  document.documentElement.setAttribute('data-theme', tema);
  localStorage.setItem('tema', tema);
  const icono = document.getElementById('themeIcon');
  icono.src = tema === 'light'
    ? 'https://cdn.jsdelivr.net/npm/lucide-static@latest/icons/sun.svg'
    : 'https://cdn.jsdelivr.net/npm/lucide-static@latest/icons/moon.svg';
}

const temaGuardado = localStorage.getItem('tema') || 'dark';
mensaTema(temaGuardado);

changeBtn.addEventListener('click', () => {
  const temaActual = document.documentElement.getAttribute('data-theme');
  const nuevoTema = temaActual === 'light' ? 'dark' : 'light';
  mensaTema(nuevoTema);
  mostrarToast(mensajesTema[nuevoTema][idiomaActual]);
});

let mouseX = null;
let mouseY = null;

document.addEventListener('mousemove', (e) => {
  mouseX = e.clientX;
  mouseY = e.clientY;
});

let iconoHovereado = null;

const skillTooltip = document.getElementById('skill-tooltip');

function actualizarHoverIconos() {
  if (mouseX !== null) {
    const elemento = document.elementFromPoint(mouseX, mouseY);
    const icono = elemento && elemento.closest('.skills-icons img');

    if (icono !== iconoHovereado) {
      if (icono && icono.title) {
        icono.classList.add('icon-hover');
        const rect = icono.getBoundingClientRect();
        skillTooltip.textContent = icono.title;
        skillTooltip.style.left = `${rect.left + rect.width / 2}px`;
        skillTooltip.style.top = `${rect.top - 5}px`;
        skillTooltip.classList.add('mostrar');
      } else {
        skillTooltip.classList.remove('mostrar');
      }
      if (iconoHovereado) iconoHovereado.classList.remove('icon-hover');
      iconoHovereado = icono;
    } else if (icono) {
      const rect = icono.getBoundingClientRect();
      skillTooltip.style.left = `${rect.left + rect.width / 2}px`;
      skillTooltip.style.top = `${rect.top - 5}px`;
    }
  }
  requestAnimationFrame(actualizarHoverIconos);
}

requestAnimationFrame(actualizarHoverIconos);

document.addEventListener('DOMContentLoaded', ajustarScrollIconos);
window.addEventListener('resize', ajustarScrollIconos);